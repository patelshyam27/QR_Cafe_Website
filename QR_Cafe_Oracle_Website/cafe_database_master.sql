-- 5(a) INNER JOIN: Bookings with customer details and table numbers
SELECT b.booking_id, c.customer_name, c.phone, t.table_number, b.booking_date, b.start_time, b.end_time, b.booking_status
FROM bookings b
INNER JOIN customers c ON b.customer_id = c.customer_id
INNER JOIN cafe_tables t ON b.table_id = t.table_id;

-- 5(b) LEFT OUTER JOIN: All cafe tables and their bookings (including tables with 0 bookings)
SELECT t.table_number, t.capacity, b.booking_id, b.booking_date, b.booking_status
FROM cafe_tables t
LEFT JOIN bookings b ON t.table_id = b.table_id
ORDER BY t.table_number;

-- 5(c) RIGHT OUTER JOIN: All customers and any bookings they have made
SELECT c.customer_id, c.customer_name, c.phone, b.booking_id, b.booking_date
FROM bookings b
RIGHT JOIN customers c ON b.customer_id = c.customer_id;

-- 5(d) FULL OUTER JOIN: All tables and all bookings matched together
SELECT t.table_number, b.booking_id, b.booking_status
FROM cafe_tables t
FULL OUTER JOIN bookings b ON t.table_id = b.table_id;


