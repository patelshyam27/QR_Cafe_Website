-- 2(a) CREATE TABLE statements with complete Integrity Constraints (Practical 4)

-- Table 1: CAFE_TABLES
CREATE TABLE cafe_tables (
    table_id     NUMBER GENERATED BY DEFAULT AS IDENTITY PRIMARY KEY,
    table_number VARCHAR2(10) NOT NULL UNIQUE,
    capacity     NUMBER DEFAULT 2 NOT NULL,
    table_status VARCHAR2(15) DEFAULT 'AVAILABLE' NOT NULL,
    CONSTRAINT chk_capacity CHECK (capacity > 0),
    CONSTRAINT chk_table_status CHECK (table_status IN ('AVAILABLE', 'RESERVED', 'DISABLED'))
);

-- Table 2: CUSTOMERS (Includes AGE for Practical 10 Age Validation Trigger)
CREATE TABLE customers (
    customer_id   NUMBER GENERATED BY DEFAULT AS IDENTITY PRIMARY KEY,
    customer_name VARCHAR2(100) NOT NULL,
    phone         VARCHAR2(15) NOT NULL UNIQUE,
    age           NUMBER DEFAULT 18,
    email         VARCHAR2(100),
    CONSTRAINT chk_customer_age CHECK (age >= 12)
);

-- Table 3: BOOKINGS
CREATE TABLE bookings (
    booking_id     NUMBER GENERATED BY DEFAULT AS IDENTITY PRIMARY KEY,
    table_id       NUMBER NOT NULL,
    customer_id    NUMBER NOT NULL,
    booking_date   DATE NOT NULL,
    start_time     VARCHAR2(5) NOT NULL,
    end_time       VARCHAR2(5) NOT NULL,
    booking_status VARCHAR2(15) DEFAULT 'CONFIRMED' NOT NULL,
    CONSTRAINT fk_booking_table FOREIGN KEY (table_id) REFERENCES cafe_tables(table_id) ON DELETE CASCADE,
    CONSTRAINT fk_booking_customer FOREIGN KEY (customer_id) REFERENCES customers(customer_id) ON DELETE CASCADE,
    CONSTRAINT chk_booking_status CHECK (booking_status IN ('CONFIRMED', 'CANCELLED', 'COMPLETED')),
    CONSTRAINT chk_start_time CHECK (REGEXP_LIKE(start_time, '^(0[0-9]|1[0-9]|2[0-3]):[0-5][0-9]$')),
    CONSTRAINT chk_end_time CHECK (REGEXP_LIKE(end_time, '^(0[0-9]|1[0-9]|2[0-3]):[0-5][0-9]$'))
);

-- Table 4: MENU_ITEMS
CREATE TABLE menu_items (
    item_id      NUMBER GENERATED BY DEFAULT AS IDENTITY PRIMARY KEY,
    item_name    VARCHAR2(100) NOT NULL UNIQUE,
    price        NUMBER(8,2) NOT NULL,
    category     VARCHAR2(30),
    availability CHAR(1) DEFAULT 'Y' NOT NULL,
    CONSTRAINT chk_item_price CHECK (price >= 0),
    CONSTRAINT chk_item_avail CHECK (availability IN ('Y', 'N'))
);

-- Table 5: CAFE_ORDERS
CREATE TABLE cafe_orders (
    order_id     NUMBER GENERATED BY DEFAULT AS IDENTITY PRIMARY KEY,
    booking_id   NUMBER NOT NULL,
    order_date   DATE DEFAULT SYSDATE NOT NULL,
    total_amount NUMBER(10,2) DEFAULT 0 NOT NULL,
    order_status VARCHAR2(15) DEFAULT 'PLACED' NOT NULL,
    CONSTRAINT fk_order_booking FOREIGN KEY (booking_id) REFERENCES bookings(booking_id) ON DELETE CASCADE,
    CONSTRAINT chk_order_total CHECK (total_amount >= 0),
    CONSTRAINT chk_order_status CHECK (order_status IN ('PLACED', 'PREPARING', 'SERVED', 'CANCELLED'))
);

-- Table 6: ORDER_ITEMS
CREATE TABLE order_items (
    order_item_id NUMBER GENERATED BY DEFAULT AS IDENTITY PRIMARY KEY,
    order_id      NUMBER NOT NULL,
    item_id       NUMBER NOT NULL,
    quantity      NUMBER DEFAULT 1 NOT NULL,
    unit_price    NUMBER(8,2) NOT NULL,
    CONSTRAINT fk_orderitem_order FOREIGN KEY (order_id) REFERENCES cafe_orders(order_id) ON DELETE CASCADE,
    CONSTRAINT fk_orderitem_menu FOREIGN KEY (item_id) REFERENCES menu_items(item_id),
    CONSTRAINT chk_item_quantity CHECK (quantity > 0),
    CONSTRAINT chk_unit_price CHECK (unit_price >= 0),
    CONSTRAINT uq_order_item UNIQUE (order_id, item_id)
);

-- Table 7: AUDIT_LOG (Used in Practical 10 Trigger)
CREATE TABLE audit_log (
    log_id        NUMBER GENERATED BY DEFAULT AS IDENTITY PRIMARY KEY,
    table_name    VARCHAR2(50) NOT NULL,
    operation     VARCHAR2(20) NOT NULL,
    change_date   DATE DEFAULT SYSDATE NOT NULL,
    performed_by  VARCHAR2(50) DEFAULT USER NOT NULL,
    details       VARCHAR2(255)
);

