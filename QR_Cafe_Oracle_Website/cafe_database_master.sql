-- 10(a) DML AUDIT TRIGGER: Automatically logs all INSERT/UPDATE/DELETE on orders
CREATE OR REPLACE TRIGGER trg_audit_orders
AFTER INSERT OR UPDATE OR DELETE ON cafe_orders
FOR EACH ROW
DECLARE
    v_op VARCHAR2(20);
    v_info VARCHAR2(255);
BEGIN
    IF INSERTING THEN
        v_op := 'INSERT';
        v_info := 'New order ID ' || :NEW.order_id || ' placed for booking ' || :NEW.booking_id;
    ELSIF UPDATING THEN
        v_op := 'UPDATE';
        v_info := 'Order ID ' || :NEW.order_id || ' status changed to ' || :NEW.order_status;
    ELSIF DELETING THEN
        v_op := 'DELETE';
        v_info := 'Order ID ' || :OLD.order_id || ' removed';
    END IF;

    INSERT INTO audit_log (table_name, operation, change_date, performed_by, details)
    VALUES ('CAFE_ORDERS', v_op, SYSDATE, USER, v_info);
END;
/

-- 10(b) VALIDATION TRIGGER: Check customer age using RAISE_APPLICATION_ERROR (Message Alert)
-- Practical Requirement: "Trigger to check the age valid or not Using Message Alert"
CREATE OR REPLACE TRIGGER trg_check_customer_age
BEFORE INSERT OR UPDATE OF age ON customers
FOR EACH ROW
BEGIN
    IF :NEW.age IS NOT NULL AND :NEW.age < 18 THEN
        -- Raises custom Oracle alert error (Code range -20000 to -20999)
        RAISE_APPLICATION_ERROR(-20001, 'AGE ALERT: Customer must be at least 18 years old to hold a cafe reservation.');
    END IF;
END;
/

-- 10(c) STORED PROCEDURE: Calculate and place order
CREATE OR REPLACE PROCEDURE sp_create_order (
    p_booking_id IN NUMBER,
    p_item_id    IN NUMBER,
    p_quantity   IN NUMBER,
    p_order_id   OUT NUMBER
) AS
    v_price NUMBER(8,2);
BEGIN
    SELECT price INTO v_price FROM menu_items WHERE item_id = p_item_id;

    INSERT INTO cafe_orders (booking_id, order_date, total_amount, order_status)
    VALUES (p_booking_id, SYSDATE, (v_price * p_quantity), 'PLACED')
    RETURNING order_id INTO p_order_id;

    INSERT INTO order_items (order_id, item_id, quantity, unit_price)
    VALUES (p_order_id, p_item_id, p_quantity, v_price);

    COMMIT;
    DBMS_OUTPUT.PUT_LINE('Order created successfully with ID: ' || p_order_id);
EXCEPTION
    WHEN NO_DATA_FOUND THEN
        DBMS_OUTPUT.PUT_LINE('Error: Item ID does not exist in Menu.');
        ROLLBACK;
    WHEN OTHERS THEN
        DBMS_OUTPUT.PUT_LINE('Error: ' || SQLERRM);
        ROLLBACK;
END;
/

-- 10(d) STORED FUNCTION: Compute total bill for a given booking
CREATE OR REPLACE FUNCTION fn_get_booking_total (
    p_booking_id IN NUMBER
) RETURN NUMBER AS
    v_total NUMBER(10,2) := 0;
BEGIN
    SELECT NVL(SUM(total_amount), 0)
    INTO v_total
    FROM cafe_orders
    WHERE booking_id = p_booking_id AND order_status != 'CANCELLED';

    RETURN v_total;
END;
/

-- 10(e) PL/SQL CURSOR DEMONSTRATION (Unit 4 Syllabus Topic)
DECLARE
    -- Explicit cursor definition
    CURSOR cur_bookings IS
        SELECT b.booking_id, c.customer_name, t.table_number, b.booking_status
        FROM bookings b
        JOIN customers c ON b.customer_id = c.customer_id
        JOIN cafe_tables t ON b.table_id = t.table_id
        WHERE b.booking_date >= TRUNC(SYSDATE);

    v_rec cur_bookings%ROWTYPE;
BEGIN
    DBMS_OUTPUT.PUT_LINE('--- TODAY & UPCOMING BOOKINGS REPORT (CURSOR DEMO) ---');
    OPEN cur_bookings;
    LOOP
        FETCH cur_bookings INTO v_rec;
        EXIT WHEN cur_bookings%NOTFOUND;
        DBMS_OUTPUT.PUT_LINE('Booking #' || v_rec.booking_id || ' | Customer: ' || v_rec.customer_name || ' | Table: ' || v_rec.table_number || ' | Status: ' || v_rec.booking_status);
    END LOOP;
    CLOSE cur_bookings;
END;
/


