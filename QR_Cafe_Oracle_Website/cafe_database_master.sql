/*
  CASE STUDY: QR Cafe Management System
  -------------------------------------
  The QR Cafe website allows customers to view cafe tables and menu items,
  book a table in advance, and place orders via QR code scan.
  
  Entities & Relationships (ER Model):
  1. CAFE_TABLES: Stores table details (table_number, capacity, status).
  2. CUSTOMERS: Stores customer identity (name, phone, age, email).
  3. BOOKINGS: Links CUSTOMER to CAFE_TABLE for a specific date and time slot (1:N).
  4. MENU_ITEMS: Items available in cafe with categories and prices.
  5. CAFE_ORDERS: Orders tied to a booking (1:N).
  6. ORDER_ITEMS: Line items mapping MENU_ITEMS to CAFE_ORDERS (M:N decomposed).
  7. AUDIT_LOG: Tracks DML changes for security and auditing (Practical 10).
  
  Normalization Status:
  - 1NF: All attributes are atomic (no repeating groups or multi-valued fields).
  - 2NF: No partial dependency (all non-key attributes fully depend on PK).
  - 3NF / BCNF: No transitive dependencies (A -> B -> C eliminated).
*/

